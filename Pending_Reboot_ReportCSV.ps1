$OutputPath = "C:\Temp\Pendind_Reboot_2026_07_27.csv"

# --- Process all computers ---
$Results = foreach ($Computer in $Computers) {
    Write-Host "Checking $Computer..." -ForegroundColor Cyan

    $Status   = "Offline"
    $User     = "N/A"
    $AD_Name  = "N/A"
    $AD_Email = "N/A"
    $Pending  = "N/A"

    # 1. Test basic network connectivity (Ping)
    if (Test-Connection -ComputerName $Computer -Count 1 -Quiet) {
        $Status = "Online (Ping OK)"

        # 2. Test if WinRM/PowerShell Remoting is accessible
        if (Test-WSMan -ComputerName $Computer -ErrorAction SilentlyContinue) {
            try {
                # Get Logged-on User
                $Cim = Get-CimInstance -ClassName Win32_ComputerSystem -ComputerName $Computer -ErrorAction Stop
                $User = $Cim.UserName

                # Query Active Directory for Name and Email
                if ($User) {
                    $Sam = $User.Split("\")[-1]
                    $ADUser = Get-ADUser -Filter { SamAccountName -eq $Sam } -Properties displayName, mail -ErrorAction SilentlyContinue
                    if ($ADUser) {
                        $AD_Name  = $ADUser.displayName
                        $AD_Email = $ADUser.mail
                    }
                }

                # Check for Pending Reboot
                $Pending = Invoke-Command -ComputerName $Computer -ScriptBlock {
                    $Path1 = "HKLM:\SOFTWARE\Microsoft\CCM\PendingReboot"
                    $Path2 = "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\WindowsUpdate\Auto Update\RebootRequired"
                    $Path3 = "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Component Based Servicing\RebootPending"
                    
                    (Test-Path $Path1) -or (Test-Path $Path2) -or (Test-Path $Path3)
                }
                $Status = "Online (Ready)"
            } catch {
                $Status = "Online (Access Denied/WMI Error)"
            }
        } else {
            $Status = "Online (WinRM Blocked/Firewall)"
        }
    }

    # Create result object
    [PSCustomObject]@{
        Date           = (Get-Date).ToString("yyyy-MM-dd HH:mm")
        Computer       = $Computer
        Status         = $Status
        LoggedOnUser   = $User
        AD_DisplayName = $AD_Name
        AD_Email       = $AD_Email
        RebootPending  = $Pending
    }
}

# --- Final Export ---
$Results | Export-Csv -Path $OutputPath -NoTypeInformation -Encoding UTF8
Write-Host "`nBulk process complete! File saved: $OutputPath" -ForegroundColor Green

